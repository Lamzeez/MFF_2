import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const cli = path.join(root, "node_modules", "supabase", "dist", "supabase.js");
const projectId = process.env.SUPABASE_PROJECT_ID;
const dbUrl = process.env.SUPABASE_DB_URL;
const genArgs = projectId
  ? [cli, "gen", "types", "typescript", "--project-id", projectId, "--schema", "public"]
  : dbUrl
    ? [cli, "gen", "types", "typescript", "--db-url", dbUrl, "--schema", "public"]
    : [cli, "gen", "types", "typescript", "--local", "--schema", "public"];

const result = spawnSync(process.execPath, genArgs, {
  cwd: root, encoding: "utf8", maxBuffer: 10 * 1024 * 1024,
});
if (result.error || result.status !== 0) {
  console.error("Database type generation failed. Provide SUPABASE_PROJECT_ID or SUPABASE_DB_URL in your environment to generate types directly from your remote Supabase project without Docker. Existing types were not changed.");
  process.exit(1);
}
if (!result.stdout.includes("export type Database")) {
  console.error("CLI returned no Database type. Existing types were not changed.");
  process.exit(1);
}
const output = "// Generated by Supabase CLI from the local public schema. Do not edit.\n" + result.stdout.replace(/\r\n/g, "\n").replace(/[\t ]+$/gm, "").trim() + "\n";
const target = path.join(root, "types", "database.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== output) {
    console.error("Database types differ from the applied schema. Run npm run db:types and review the diff.");
    process.exit(1);
  }
  console.log("Database types match the applied schema.");
} else {
  writeFileSync(target, output);
  console.log("Generated types/database.ts from the local database.");
}
