import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {
  sanitizeProfileUrl,
  DEFAULT_COVER_PHOTO,
} from "../../lib/customer-profile";
import { uploadCustomerProfilePhoto } from "../../services/storage";
import { formatNotificationTimestamp } from "../../services/notifications";

test("formatNotificationTimestamp formats date into 'mm-dd · hh:mm A' format", () => {
  const d = new Date(2026, 10, 17, 19, 24); // Nov 17, 2026, 7:24 PM
  const formatted = formatNotificationTimestamp(d);
  assert.ok(formatted.startsWith("11-17"), `Expected timestamp to start with '11-17', got: ${formatted}`);
  assert.ok(formatted.includes("7:24") || formatted.includes("19:24"), `Expected timestamp to include time, got: ${formatted}`);
});

test("sanitizeProfileUrl correctly discards ephemeral blob and file URIs", () => {
  // Ephemeral blob URLs generated by browser ImagePicker
  assert.equal(
    sanitizeProfileUrl("blob:http://localhost:8081/123e4567-e89b-12d3-a456-426614174000", DEFAULT_COVER_PHOTO),
    DEFAULT_COVER_PHOTO
  );

  assert.equal(
    sanitizeProfileUrl("blob:https://mati-foodfinder.com/photo-uuid", null),
    null
  );

  // Temporary local app cache file URIs
  assert.equal(
    sanitizeProfileUrl("file:///data/user/0/host.exp.exponent/cache/ExperienceData/ImagePicker/test.jpg", null),
    null
  );

  // Permanent remote Supabase Storage public HTTPS URLs are preserved
  const validSupabaseUrl = "https://tqztlckmeznbsjcszzyg.supabase.co/storage/v1/object/public/foodie-uploads/customer-profiles/user_123/cover/12345.jpg";
  assert.equal(
    sanitizeProfileUrl(validSupabaseUrl, DEFAULT_COVER_PHOTO),
    validSupabaseUrl
  );

  // Unsplash and remote URLs are preserved
  const validUnsplash = "https://images.unsplash.com/photo-1507525428034-b723cf961d3e?w=1200";
  assert.equal(
    sanitizeProfileUrl(validUnsplash, DEFAULT_COVER_PHOTO),
    validUnsplash
  );

  // Null, undefined, empty fallback
  assert.equal(sanitizeProfileUrl(null, DEFAULT_COVER_PHOTO), DEFAULT_COVER_PHOTO);
  assert.equal(sanitizeProfileUrl("", DEFAULT_COVER_PHOTO), DEFAULT_COVER_PHOTO);
  assert.equal(sanitizeProfileUrl("   ", DEFAULT_COVER_PHOTO), DEFAULT_COVER_PHOTO);
});

